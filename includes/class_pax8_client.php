<?php

/*
 * ITFlow - Pax8 API client (roadmap #25: cost sync for billing/COGS reconciliation).
 *
 * IMPORTANT, read before touching: this environment has no real Pax8 Partner API credentials,
 * so nothing here has ever been exercised against Pax8's actual servers. It is built from Pax8's
 * publicly documented Partner API (OAuth2 client-credentials grant via Pax8's Auth0 tenant,
 * /companies, /subscriptions) and verified only against a loopback fake-Pax8 server
 * (tests/support/fake_pax8_router.php). Pax8's exact response field names are the LEAST certain
 * of the three billing integrations built this session (QBO/Xero's wire shapes are well
 * established; Pax8's is inferred from documentation, not hands-on API access) - flagging this
 * plainly: double-check the real response shape against Pax8's current API reference before
 * relying on this in production, and treat the field names below as a best-effort starting
 * point rather than a verified contract.
 *
 * Auth is OAuth2 CLIENT CREDENTIALS (machine-to-machine, no browser redirect, no per-admin
 * authorization step) - simpler than QBO/Xero's authorization-code flow. One pair of API
 * credentials (generated by the partner in the Pax8 Partner Portal) is entered once in
 * admin/settings_pax8.php and the access token is fetched/refreshed server-side exactly like a
 * service account.
 *
 * Mirrors includes/class_unifi.php's shape (constructor reads its own integration row, throws
 * RuntimeException on any setup/transport problem) rather than the accounting client's
 * AccountingClientInterface shape - this is a PULL-only integration (cost data in, never pushing
 * anything to Pax8), so there is no shared push-sync orchestration to slot into.
 */

class Pax8Exception extends RuntimeException {}

class Pax8Client {

    const TOKEN_URL = 'https://login.pax8.com/oauth/token';
    const API_BASE  = 'https://api.pax8.com/v1';
    // Pax8's Auth0 tenant requires an audience claim identifying which API the token is for.
    const AUDIENCE  = 'api://p8p.client';

    private mysqli $mysqli;
    private int $integration_id;
    private string $client_id;
    private string $client_secret;
    private array $integration;

    // Test-injectability only (see class header) - null means "use the real constants".
    private ?string $token_url_override;
    private ?string $api_base_override;

    public function __construct(mysqli $mysqli, int $integration_id, array $url_overrides = []) {
        $this->mysqli = $mysqli;
        $id = intval($integration_id);
        $row = mysqli_fetch_assoc(mysqli_query($mysqli, "SELECT * FROM pax8_integrations WHERE id = $id LIMIT 1"));
        if (!$row) {
            throw new Pax8Exception("Pax8 integration $id not found");
        }
        $this->integration    = $row;
        $this->integration_id = $id;
        $this->client_id      = (string) ($row['client_id'] ?? '');
        $this->client_secret  = decryptSetting((string) ($row['client_secret_enc'] ?? ''));
        $this->token_url_override = $url_overrides['token_url'] ?? null;
        $this->api_base_override  = $url_overrides['api_base'] ?? null;
        if ($this->client_id === '' || $this->client_secret === '') {
            throw new Pax8Exception("Pax8 integration $id has no decryptable client id/secret");
        }
    }

    private function tokenUrl(): string {
        return $this->token_url_override ?? self::TOKEN_URL;
    }

    private function apiBase(): string {
        return $this->api_base_override ?? self::API_BASE;
    }

    /** Return a valid access token, fetching a fresh one if missing or within 2 minutes of expiry. */
    public function getAccessToken(): string {
        $expires_at = $this->integration['token_expires_at'] ?? null;
        $access     = decryptSetting((string) ($this->integration['access_token_enc'] ?? ''));
        $needs_fetch = empty($access) || empty($expires_at) || strtotime($expires_at) <= (time() + 120);
        if (!$needs_fetch) {
            return $access;
        }
        return $this->fetchAccessToken();
    }

    private function fetchAccessToken(): string {
        $ch = curl_init($this->tokenUrl());
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_POST, true);
        curl_setopt($ch, CURLOPT_HTTPHEADER, ['Content-Type: application/json', 'Accept: application/json']);
        curl_setopt($ch, CURLOPT_POSTFIELDS, json_encode([
            'grant_type'    => 'client_credentials',
            'client_id'     => $this->client_id,
            'client_secret' => $this->client_secret,
            'audience'      => self::AUDIENCE,
        ]));
        curl_setopt($ch, CURLOPT_TIMEOUT, 20);

        $raw       = curl_exec($ch);
        $curl_err  = curl_error($ch);
        $http_code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);

        if ($raw === false || $http_code < 200 || $http_code >= 300) {
            $reason = !empty($curl_err) ? $curl_err : "HTTP $http_code";
            throw new Pax8Exception("Pax8 token request failed: $reason");
        }
        $json = json_decode($raw, true);
        if (!is_array($json) || empty($json['access_token'])) {
            throw new Pax8Exception('Pax8 token request failed: access token missing from response.');
        }

        $access     = (string) $json['access_token'];
        $expires_in = intval($json['expires_in'] ?? 3600);
        $expires_at = date('Y-m-d H:i:s', time() + $expires_in);

        $access_esc  = mysqli_real_escape_string($this->mysqli, encryptSetting($access));
        $expires_esc = mysqli_real_escape_string($this->mysqli, $expires_at);
        mysqli_query($this->mysqli, "UPDATE pax8_integrations SET access_token_enc = '$access_esc', token_expires_at = '$expires_esc' WHERE id = $this->integration_id");
        $this->integration['access_token_enc'] = encryptSetting($access);
        $this->integration['token_expires_at'] = $expires_at;

        return $access;
    }

    private function get(string $path): array {
        $token = $this->getAccessToken();
        $url   = $this->apiBase() . '/' . ltrim($path, '/');
        $ch = curl_init($url);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_HTTPHEADER, [
            'Authorization: Bearer ' . $token,
            'Accept: application/json',
        ]);
        curl_setopt($ch, CURLOPT_TIMEOUT, 30);

        $raw       = curl_exec($ch);
        $curl_err  = curl_error($ch);
        $http_code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        curl_close($ch);

        if ($raw === false) {
            throw new Pax8Exception("Pax8 API transport error: $curl_err");
        }
        if ($http_code < 200 || $http_code >= 300) {
            throw new Pax8Exception("Pax8 API error HTTP $http_code on GET $path: " . substr((string) $raw, 0, 400));
        }
        $json = json_decode($raw, true);
        return is_array($json) ? $json : [];
    }

    /**
     * Quick credential check for the admin "Test Connection" button - a cheap call that
     * succeeds only with a genuinely valid token.
     */
    public function testConnection(): bool {
        $this->get('companies?limit=1');
        return true;
    }

    /**
     * List every Pax8 company (the partner's end-customers) this API credential can see.
     * Returns [['id'=>string,'name'=>string], ...]. Paginates until a short page is returned.
     */
    public function getCompanies(): array {
        $out = [];
        $offset = 0;
        $limit = 200;
        do {
            $res = $this->get("companies?limit=$limit&offset=$offset");
            $page = $res['content'] ?? $res['data'] ?? [];
            foreach ($page as $c) {
                $out[] = [
                    'id'   => (string) ($c['id'] ?? ''),
                    'name' => (string) ($c['name'] ?? ''),
                ];
            }
            $offset += $limit;
        } while (count($page) === $limit && $offset < 5000); // hard stop - never loop forever on an unexpected shape
        return $out;
    }

    /**
     * List every active subscription for one Pax8 company - the actual COGS data. Returns
     * [['id'=>string,'companyId'=>string,'productName'=>string,'quantity'=>int,
     *   'unitCost'=>float,'totalCost'=>float,'billingTerm'=>string,'status'=>string], ...]
     */
    public function getSubscriptionsForCompany(string $companyId): array {
        $companyId = rawurlencode($companyId);
        $out = [];
        $offset = 0;
        $limit = 200;
        do {
            $res = $this->get("subscriptions?companyId=$companyId&limit=$limit&offset=$offset");
            $page = $res['content'] ?? $res['data'] ?? [];
            foreach ($page as $s) {
                $qty = (int) ($s['quantity'] ?? 1);
                // Pax8's pricing block shape is the least certain part of this client (see class
                // header) - tolerate a couple of plausible shapes rather than assuming one.
                $unitCost = (float) ($s['billingTerm']['price']['total'] ?? $s['price']['unitCost'] ?? $s['unitCost'] ?? 0);
                $out[] = [
                    'id'          => (string) ($s['id'] ?? ''),
                    'companyId'   => (string) ($s['companyId'] ?? ''),
                    'productName' => (string) ($s['product']['name'] ?? $s['productName'] ?? ''),
                    'quantity'    => $qty,
                    'unitCost'    => $unitCost,
                    'totalCost'   => round($unitCost * $qty, 2),
                    'billingTerm' => (string) ($s['billingTerm']['term'] ?? $s['term'] ?? 'MONTHLY'),
                    'status'      => (string) ($s['status'] ?? 'ACTIVE'),
                ];
            }
            $offset += $limit;
        } while (count($page) === $limit && $offset < 5000);
        return $out;
    }
}
